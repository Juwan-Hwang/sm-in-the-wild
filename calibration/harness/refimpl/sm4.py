    x.append(x[0] ^ _t(x[1] ^ x[2] ^ x[3] ^ rk[0]))
    print(f"  ours X[4] = {x[4]:08X}   standard 27FAD345   match={x[4]==0x27FAD345}")

    print()
    print("=== final ciphertext (Example 1) ===")
    ct = encrypt_block(pt, rk)
    print(f"  ours : {h(ct)}")
    print(f"  std  : 681EDF34D206965E86B3E94F536E4246")
    print(f"  match: {h(ct)=='681EDF34D206965E86B3E94F536E4246'}")

    print()
    print("=== round-trip ===")
    back = decrypt_block(ct, rk)
    print(f"  decrypt(encrypt(x)) == x : {back == pt}")

