#!/usr/bin/env bash
# Build docs/paper.md in the official USENIX template and measure the page limit.
#
#   paper/build.sh   -> paper/out/paper.pdf (named-author preprint), and prints
#                       "body ends on page N of T (limit 13)" plus where the required
#                       appendices, the references and Appendix A start.
#
# Needs pandoc (>= 3.1) and pdflatex with booktabs, tabularx, fvextra, placeins,
# microtype, pslatex, breakurl, cite (texlive-latex-recommended + -extra) and pdfinfo.
# CJK ideographs (two references, one code span): pdflatex cannot load an OpenType CJK
# font and the host has no xeCJK/xelatex or CJKutf8, so each CJK run is drawn as vector
# glyphs from Noto Serif CJK SC by cjk_glyphs.py (python3 + fontTools) into an n-em PDF
# snippet and included in place; the page metrics are those of the same-width box used
# before. The font is NotoSerifCJKsc-Regular.otf (SIL OFL, ~24 MB, from
# github.com/notofonts/noto-cjk, Serif/OTF/SimplifiedChinese), looked up at $CJK_FONT and
# then /workspace/.tools/fonts/. Without it the runs fall back to grey same-width boxes and
# the build says so: the submitted PDF needs the font (or a xelatex+xeCJK build).
# The body-end label is placed after \FloatBarrier, so every body float is counted in the
# body. paper/out/ is not committed.
set -euo pipefail
cd "$(dirname "$0")"
OUT=out
mkdir -p "$OUT"
cp usenix-2020-09.sty "$OUT/"
cp ../docs/figures/funnel.pdf "$OUT/"   # Figure 1, generated by harness/screen/draw_funnel.py
CJK_FONT="${CJK_FONT:-/workspace/.tools/fonts/NotoSerifCJKsc-Regular.otf}"
if [ -f "$CJK_FONT" ] && python3 -c "import fontTools" 2>/dev/null; then export CJK_MODE=glyphs; else
  export CJK_MODE=boxes
  echo "WARNING: CJK font not found ($CJK_FONT) or fontTools missing: CJK runs drawn as boxes" >&2
fi
python3 - <<'PY'
import re, pathlib
import os
src = pathlib.Path("../docs/paper.md").read_text(encoding="utf-8")
cjk = re.compile(r"[\u3000-\u303f\u4e00-\u9fff\uff00-\uffef]+")
runs_seen = []
def box(run):
    if os.environ.get("CJK_MODE") != "glyphs":
        return "`\\cjkbox{%d}`{=latex}" % len(run)
    if run not in runs_seen:
        runs_seen.append(run)
    return "`\\cjkimg{%d}`{=latex}" % runs_seen.index(run)
def code_fix(m):
    # a code span holding CJK becomes one raw \texttt{...}: splitting it into several code
    # spans around raw inlines puts two backticks side by side, which pandoc reads as a
    # double-backtick delimiter (the old build printed "{=latex}" into Section 2.2)
    s = m.group(0)[1:-1].replace("\n", " ")
    if not cjk.search(s):
        return m.group(0)
    esc = lambda t: "".join({"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$",
                             "&": r"\&", "#": r"\#", "^": r"\^{}", "_": r"\_", "%": r"\%",
                             "~": r"\~{}"}.get(c, c) for c in t)
    parts, runs, out = cjk.split(s), cjk.findall(s), []
    for i, p in enumerate(parts):
        out.append(esc(p))
        if i < len(runs):
            out.append(box(runs[i])[1:-len("`{=latex}")])
    return "`\\texttt{" + "".join(out) + "}`{=latex}"
# a code span may wrap across a source line (the one in Section 2.2 does); it may not
# start or end inside a ``` fence
src = re.sub(r"(?<!`)`(?!`)[^`]+`(?!`)", code_fix, src)
src = cjk.sub(lambda m: box(m.group(0)), src)
pathlib.Path("out/paper.pre.md").write_text(src, encoding="utf-8")
pathlib.Path("out/cjk_runs.txt").write_text("\n".join(runs_seen), encoding="utf-8")
PY
if [ "$CJK_MODE" = glyphs ] && [ -s "$OUT/cjk_runs.txt" ]; then
  mapfile -t RUNS < "$OUT/cjk_runs.txt"
  python3 cjk_glyphs.py "$CJK_FONT" "$OUT/cjk" "${RUNS[@]}"
fi
pandoc "$OUT/paper.pre.md" -f markdown-implicit_figures+raw_attribute \
  --lua-filter=usenix-preprint.lua --template=template.tex --no-highlight --wrap=none -o "$OUT/paper.tex"
( cd "$OUT" && for i in 1 2; do
    pdflatex -interaction=nonstopmode -halt-on-error paper.tex >/dev/null || { tail -40 paper.log; exit 1; }
  done )
python3 - <<'PY'
import re, pathlib, subprocess
aux = pathlib.Path("out/paper.aux").read_text()
def page(lbl):
    m = re.search(r"\\newlabel\{%s\}\{\{[^}]*\}\{(\d+)\}" % lbl, aux)
    return int(m.group(1)) if m else None
info = subprocess.run(["pdfinfo", "out/paper.pdf"], capture_output=True, text=True).stdout
total = int(re.search(r"Pages:\s+(\d+)", info).group(1))
b, e, r, a = page("bodyend"), page("ethicsstart"), page("refsstart"), page("appstart")
print(f"body ends on page {b} of {total} (limit 13); Ethical Considerations starts p.{e}; "
      f"references start p.{r}; Appendix A starts p.{a}")
pathlib.Path("out/pages.txt").write_text(
    f"bodyend={b}\nethics={e}\nrefs={r}\nappendix={a}\ntotal={total}\n")
PY
